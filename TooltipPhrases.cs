using System;

namespace LotteryTax;

public static class TooltipPhrases
{
    private static readonly Random Rng = new();

    // (верхняя граница включительно | null = «и выше», пул фраз)
    private static readonly (decimal? Max, string[] Phrases)[] Ranges =
    {
        (10m, new[] { "И даже это деньги", "Сдачи не надо" }),
        (50m, new[] { "А хватит ли этого на пирожок?", "Пирожок с капустой, но без компота" }),
        (100m, new[] { "А поехали на автобусе?", "Трамвай туда-обратно, и ещё на мороженое" }),
        (500m, new[] { "Инвестиции в лотерею окупились", "Наконец-то шаурма!" }),
        (1_000m, new[] { "Вечером зайду в \"Пятёрочку\"", "Ужин будет. Скромный" }),
        (5_000m, new[]
        {
            "Буду месяц играть, не вкладывая ни рубля",
            "Чехол на телефон + стекло!",
            "Одна поездка в \"Пятёрочку\" без калькулятора"
        }),
        (10_000m, new[] { "Надо чаще играть, играть надо чаще", "Отпуск в Сочи. Без отеля" }),
        (50_000m, new[] { "На ла-бу-те-нах, нах!", "Гардероб обновится. В секонде" }),
        (100_000m, new[] { "В этом месяце можно не работать", "Можно взять пару дней и подумать" }),
        (250_000m, new[] { "Можно наконец-то починить машину", "Ремонт в ванной. Малой кровью" }),
        (500_000m, new[] { "Отпуск! Настоящий! С отелем!", "Можно уже и в Турцию" }),
        (1_000_000m, new[] { "Всё пропью!", "Кто-нибудь остановите меня!" }),
        (2_000_000m, new[] { "И этот день настал!", "Мам, я в порядке. Правда." }),
        (3_500_000m, new[] { "На машину хватит. На бензин — нет", "Можно и в ипотеку вписаться" }),
        (5_000_000m, new[] { "О квартире помечтать. В регионе", "В Москве — за МКАДом" }),
        (7_500_000m, new[] { "Уже можно не здороваться с соседями", "Переезд в новостройку. С ремонтом!" }),
        (10_000_000m, new[] { "Держись, Авито, я покупаю студию!", "Можно и двушку. Почти в центре" }),
        (50_000_000m, new[] { "Осторожно, теперь я инвестор!", "Банк сам позвонит. Не я ему" }),
        (100_000_000m, new[] { "Покупаю остров. Маленький. Но свой", "Летаю бизнес-классом. Даже в Тулу" }),
        (null, new[] { "Кто вообще играет в такую лотерею?!", "Дальше — только с юристами и охраной" }),
    };

    public static string For(decimal net)
    {
        if (net <= 0m)
            return "Да пошли все эти лотереи!";

        foreach (var (max, phrases) in Ranges)
        {
            if (max is null || net <= max.Value)
                return phrases[Rng.Next(phrases.Length)];
        }
        // недостижимо (последний диапазон — null), но компилятор требует return
        return Ranges[^1].Phrases[0];
    }
}